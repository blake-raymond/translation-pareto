export const TARGET_CODES = LANGUAGES.map((item) => item.code).filter((code) => code !== "en");

export function languageLabel(language) {
  if (!language) return "";
  if (language.native === language.english) return language.english;
  return `${language.native} (${language.english})`;
}

export function languageName(code) {
  const language = LANGUAGES.find((item) => item.code === code);
  return languageLabel(language) || code;
}

